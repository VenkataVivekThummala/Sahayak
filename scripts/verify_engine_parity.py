"""
Engine cross-validation harness running 500 random fact combinations per scheme (3,500 total).
Verifies 100% decision and missing_fields parity between Python and TypeScript rule engines.
"""
import json
import random
import subprocess
import sys
from pathlib import Path

# Add project root to sys.path
root_dir = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(root_dir))

from backend.app.knowledge import load_schemes, load_fields
from backend.app.eligibility.engine import check_eligibility

def generate_random_facts(fields_def: dict) -> dict:
    facts = {}
    for f_name, f_spec in fields_def.items():
        # 35% chance of omitting the field to thoroughly test unknown handling & missing fields
        if random.random() < 0.35:
            continue
        if f_spec["type"] == "bool":
            facts[f_name] = random.choice([True, False])
        elif f_spec["type"] == "number":
            min_v = f_spec.get("min", 0)
            max_v = f_spec.get("max", 100)
            if f_name == "age":
                facts[f_name] = random.choice([15, 58, 59, 60, 62, 65, 70, 75, 85])
            elif f_name == "girl_child_age":
                facts[f_name] = random.choice([0, 5, 8, 10, 11, 15, 18])
            elif f_name == "annual_income":
                facts[f_name] = random.choice([50000, 100000, 249999, 250000, 250001, 500000])
            else:
                facts[f_name] = random.randint(min_v, min(max_v, 100))
    return facts

def main():
    schemes = load_schemes()
    fields_def = load_fields()

    random.seed(42)
    test_cases = []

    for s in schemes:
        sid = s["scheme_id"]
        for i in range(500):
            facts = generate_random_facts(fields_def)
            py_res = check_eligibility(sid, facts, lang="en")
            test_cases.append({
                "scheme_id": sid,
                "facts": facts,
                "py_status": py_res["status"],
                "py_missing": py_res["missing_fields"],
                "py_warnings_count": len(py_res["warnings"])
            })

    output_json = root_dir / "data" / "parity_cases_3500.json"
    with open(output_json, "w", encoding="utf-8") as f:
        json.dump(test_cases, f)

    print(f"Generated {len(test_cases)} cross-validation cases across {len(schemes)} schemes.")

    # Write Jest test file in mobile/tests/fuzzy_parity.test.ts
    test_file = root_dir / "mobile" / "tests" / "fuzzy_parity.test.ts"
    test_content = f"""/**
 * High-Scale Cross-Validation Test (3,500 cases)
 * Generated by scripts/verify_engine_parity.py
 */
import * as fs from "fs";
import * as path from "path";
import {{ checkEligibilityOffline, SchemeRecord }} from "../src/engine/engine";

describe("3,500-Iteration High-Scale Parity Suite", () => {{
  const dataDir = path.resolve(__dirname, "../../data");
  const schemesData: SchemeRecord[] = JSON.parse(
    fs.readFileSync(path.join(dataDir, "schemes.json"), "utf-8")
  );
  const cases = JSON.parse(
    fs.readFileSync(path.join(dataDir, "parity_cases_3500.json"), "utf-8")
  );
  const schemesById = new Map<string, SchemeRecord>();
  for (const s of schemesData) {{
    schemesById.set(s.scheme_id, s);
  }}

  test("Evaluates all 3,500 random cases with 100% equivalence to Python", () => {{
    let passed = 0;
    let failed = 0;
    const failures: string[] = [];

    for (let i = 0; i < cases.length; i++) {{
      const c = cases[i];
      const scheme = schemesById.get(c.scheme_id)!;
      const res = checkEligibilityOffline(scheme, c.facts, "en");

      if (res.status !== c.py_status) {{
        failed++;
        failures.push(`Case ${{i}} (${{c.scheme_id}}) status mismatch: py=${{c.py_status}}, ts=${{res.status}}`);
      }} else if (JSON.stringify(res.missing_fields) !== JSON.stringify(c.py_missing)) {{
        failed++;
        failures.push(`Case ${{i}} (${{c.scheme_id}}) missing_fields mismatch: py=${{JSON.stringify(c.py_missing)}}, ts=${{JSON.stringify(res.missing_fields)}}`);
      }} else {{
        passed++;
      }}
    }}

    expect(failures).toEqual([]);
    expect(passed).toBe(3500);
    expect(failed).toBe(0);
  }});
}});
"""
    with open(test_file, "w", encoding="utf-8") as f:
        f.write(test_content)

    print("Running Jest test suite on 3,500 cases...")
    result = subprocess.run(
        ["npm.cmd", "test", "--", "fuzzy_parity.test.ts"],
        cwd=str(root_dir / "mobile"),
        capture_output=True,
        text=True
    )
    print(result.stdout)
    if result.stderr:
        print(result.stderr)

    if result.returncode == 0:
        print("SUCCESS: 3,500 / 3,500 cases matched Python engine with 100.0% parity!")
    else:
        print("ERROR: Parity test failed.")
        sys.exit(1)

if __name__ == "__main__":
    main()
